/**
 * Bakes glyph outlines from Rajdhani SemiBold (SIL OFL 1.1) for the profile card in
 * packages/exporters/src/card.ts. The card draws its text as vector outlines, so it looks the same
 * on every machine and does not depend on installed fonts.
 *
 *   pnpm exec tsx scripts/bake-card-font.ts .starforge/cache/rajdhani/Rajdhani-SemiBold.ttf "Rajdhani SemiBold"
 *
 * Writes packages/exporters/src/card-font-data.ts.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = join(ROOT, 'packages', 'exporters', 'src', 'card-font-data.ts');

/** Printable ASCII, and the few other characters the card draws. */
const CHARACTERS = [
  ...Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)),
  '\u00b7',
  '\u2014',
  '\u2026',
];

interface PathCommand {
  type: string;
  x?: number;
  y?: number;
  x1?: number;
  y1?: number;
  x2?: number;
  y2?: number;
}

interface Glyph {
  advanceWidth?: number;
  path: { commands: PathCommand[] };
  getBoundingBox(): { y2: number };
}

/** SVG path data in whole font units, with y flipped so the glyph stands upright in SVG. */
function toPath(commands: PathCommand[]): string {
  const x = (v: number | undefined): number => Math.round(v ?? 0);
  const y = (v: number | undefined): number => -Math.round(v ?? 0);
  return commands
    .map((c) => {
      switch (c.type) {
        case 'M':
          return `M${x(c.x)} ${y(c.y)}`;
        case 'L':
          return `L${x(c.x)} ${y(c.y)}`;
        case 'Q':
          return `Q${x(c.x1)} ${y(c.y1)} ${x(c.x)} ${y(c.y)}`;
        case 'C':
          return `C${x(c.x1)} ${y(c.y1)} ${x(c.x2)} ${y(c.y2)} ${x(c.x)} ${y(c.y)}`;
        case 'Z':
          return 'Z';
        default:
          return '';
      }
    })
    .join('');
}

async function main(): Promise<void> {
  const file = process.argv[2];
  if (!file) throw new Error('Usage: pnpm exec tsx scripts/bake-card-font.ts <font.ttf> [label]');
  const data = await readFile(resolve(file));
  const font = opentype.parse(
    data.buffer.slice(data.byteOffset, data.byteOffset + data.byteLength),
  );
  const label = process.argv[3] ?? basename(file);
  const hasChar = (font as unknown as { hasChar?: (c: string) => boolean }).hasChar;

  const missing: string[] = [];
  let pathBytes = 0;
  const entries = CHARACTERS.map((char) => {
    if (hasChar && !hasChar.call(font, char)) missing.push(JSON.stringify(char));
    const glyph = font.charToGlyph(char) as unknown as Glyph;
    const d = toPath(glyph.path.commands);
    pathBytes += d.length;
    return `    ${JSON.stringify(char)}: { advance: ${Math.round(glyph.advanceWidth ?? 0)}, d: ${JSON.stringify(d)} },`;
  });
  const capHeight = Math.round((font.charToGlyph('H') as unknown as Glyph).getBoundingBox().y2);

  await writeFile(
    OUTPUT,
    `// Generated by scripts/bake-card-font.ts. Do not edit by hand.
//
// Glyph outlines from ${label}, licensed under the SIL Open Font License 1.1. Copyright (c) 2014
// Indian Type Foundry (info@indiantypefoundry.com). See THIRD_PARTY_NOTICES.md and
// licenses/Rajdhani-OFL-1.1.txt. This file holds vector outlines for drawing text, not a font;
// scripts/bake-card-font.ts rebuilds it from the original font.
//
// Each glyph is SVG path data in font units, drawn upright (y already flipped, baseline at 0),
// and its advance width.

export const CARD_FONT: {
  name: string;
  unitsPerEm: number;
  /** Height of a capital letter above the baseline, in font units. */
  capHeight: number;
  glyphs: Record<string, { advance: number; d: string }>;
} = {
  name: ${JSON.stringify(label)},
  unitsPerEm: ${font.unitsPerEm},
  capHeight: ${capHeight},
  glyphs: {
${entries.join('\n')}
  },
};
`,
  );
  console.log(
    `baked ${CHARACTERS.length} glyphs, ${pathBytes} bytes of path data from ${label} (${font.unitsPerEm} units per em, cap height ${capHeight})`,
  );
  console.log(
    missing.length ? `missing from the font: ${missing.join(' ')}` : 'no missing characters',
  );
  console.log(`wrote ${OUTPUT}`);
}

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
